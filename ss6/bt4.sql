    hotel_id,
    COUNT(*) AS status_completed,
    AVG(total_price) AS avg_total_price
FROM bookings
WHERE status = 'COMPLETED'
GROUP BY hotel_id
HAVING 
    COUNT(*) >= 50
    AND AVG(total_price) > 3000000;
    
