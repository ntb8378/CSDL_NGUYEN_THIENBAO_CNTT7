    hotel_id,
    SUM(CASE WHEN status = 'COMPLETED' THEN 1 ELSE 0 END) AS status_completed,
    AVG(CASE WHEN status = 'COMPLETED' THEN total_price END) AS avg_total_price
FROM bookings
GROUP BY hotel_id
HAVING 
    SUM(CASE WHEN status = 'COMPLETED' THEN 1 ELSE 0 END) >= 50
    AND AVG(CASE WHEN status = 'COMPLETED' THEN total_price END) > 3000000;
